#!/usr/bin/env -S deno run -A
// Regenerate src/vendor/lucide-preact.mjs from the names icons.tsx imports.
//
// The browser maps the bare specifier `lucide-preact` to this vendored subset
// (index.html's import map), so it must export every name icons.tsx imports —
// a missing one is a page-load 404 on the export, and forgetting to hand-vendor
// a newly-imported icon took the fleet UI down (S-16980, MessageCircle). This
// removes the hand-edit: the subset is DERIVED from the imports, so it cannot
// drift. Run it after adding an icon to icons.tsx; the output is committed (no
// build step at serve time — this is bin/backup's pattern, run by hand, output
// in git). Both halves come from `npm:lucide-preact` at the version deno.json
// pins: the runtime is its own dist modules inlined, each icon its own node.

let root = new URL('../', import.meta.url)
let iconsTsx = new URL('src/components/icons.tsx', root)
let out = new URL('src/vendor/lucide-preact.mjs', root)

// The PascalCase names icons.tsx imports from lucide-preact, minus the type-only
// `type LucideIcon` (erased before the browser, so it needs no runtime export).
let imported = (src: string): string[] => {
  let clause = src.match(/import\s*\{([^}]*)\}\s*from\s*['"]lucide-preact['"]/)
  if (!clause) throw new Error('no lucide-preact import found in icons.tsx')
  return clause[1]
    .split(',')
    .map((s) => s.trim())
    .filter((s) => s && !s.startsWith('type '))
    .sort()
}

// A lucide component builds `h(Icon, {iconNode, class})` when called with no
// props, so calling it hands back both halves we need to re-emit it: the node
// array, and the canonical kebab name — the LAST `lucide-` class token, since
// createLucideIcon appends `lucide-${rawName}` after the normalized one (they
// differ for names like Columns3 → "columns-3", equal ones dedupe to one).
let describe = (
  Component: unknown,
) => {
  if (typeof Component != 'function') throw new Error('not a lucide icon')
  let { iconNode, class: cls } = Component({}).props
  let name = String(cls).split(/\s+/).at(-1)!.replace('lucide-', '')
  return { name, node: iconNode }
}

// A dist runtime module, stripped to its declarations: drop the license block,
// the sourcemap line, and every import/export — the symbols they name are
// supplied by a sibling module we also inline, or by the preact imports we
// hoist. Their `import … from 'preact'|'preact/hooks'` names are collected so
// the bundle re-declares exactly the ones the runtime uses.
let preact = new Set<string>()
let hooks = new Set<string>()
let collect = (into: Set<string>, line: string) => {
  let m = line.match(/import\s*\{([^}]*)\}/)
  if (m) { for (let n of m[1].split(',')) into.add(n.trim()) }
}
let strip = (src: string): string =>
  src
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .split('\n')
    .filter((l) => {
      if (/from\s*['"]preact['"]/.test(l)) return collect(preact, l), false
      if (/from\s*['"]preact\/hooks['"]/.test(l)) {
        return collect(hooks, l), false
      }
      return !/^\s*(import|export)\b/.test(l) &&
        !/^\s*\/\/# sourceMappingURL/.test(l)
    })
    .join('\n')
    .trim()

// The runtime, in dependency order, read from the same dist the icons come from.
let esm = new URL('.', import.meta.resolve('lucide-preact'))
let runtime = [
  'shared/src/utils/mergeClasses.mjs',
  'shared/src/utils/hasA11yProp.mjs',
  'shared/src/utils/toCamelCase.mjs',
  'shared/src/utils/toPascalCase.mjs',
  'shared/src/utils/toKebabCase.mjs',
  'defaultAttributes.mjs',
  'context.mjs',
  'Icon.mjs',
  'createLucideIcon.mjs',
]

let src = await Deno.readTextFile(iconsTsx)
let names = imported(src)
let lucide: Record<string, unknown> = await import('lucide-preact')

let bodies = await Promise.all(
  runtime.map(async (p) => strip(await Deno.readTextFile(new URL(p, esm)))),
)
let icons = names.map((name) => {
  let { name: kebab, node } = describe(lucide[name])
  return `let ${name} = createLucideIcon(${JSON.stringify(kebab)}, ${
    JSON.stringify(node)
  })`
})

let version = import.meta.resolve('lucide-preact').match(
  /lucide-preact\/([\d.]+)/,
)?.[1]
let text = [
  `// GENERATED by \`deno task icons\` from npm:lucide-preact@${version} — do not edit.`,
  `// The vendored subset icons.tsx imports; regenerate after adding an icon.`,
  `// @license lucide-preact v${version} — ISC (github.com/lucide-icons/lucide).`,
  ``,
  `import { ${[...preact].sort().join(', ')} } from 'preact'`,
  `import { ${[...hooks].sort().join(', ')} } from 'preact/hooks'`,
  ``,
  bodies.join('\n\n'),
  ``,
  icons.join('\n'),
  ``,
  `export { ${names.join(', ')} }`,
  ``,
].join('\n')

await Deno.writeTextFile(out, text)
console.log(`wrote ${names.length} icons to ${out.pathname}`)
