// Rebuild the checked-in browser runtime from workspace sources. Run from any
// directory; keep the output free of machine-specific paths and generated lint.
const directory = new URL('.', import.meta.url)
const deno = async (...args: string[]) => {
  const result = await new Deno.Command(Deno.execPath(), {
    args,
    cwd: directory,
    stdout: 'inherit',
    stderr: 'inherit',
  }).output()
  if (!result.success) throw new Error(`deno ${args.join(' ')} failed`)
}
await deno('bundle', '--platform', 'browser', 'runtime.ts', '-o', 'runtime.js')
const output = new URL('runtime.js', directory)
const source = await Deno.readTextFile(output)
await Deno.writeTextFile(
  output,
  '// deno-lint-ignore-file -- Generated by build.ts; edit runtime.ts or its sources.\n' +
    source,
)
await deno('fmt', 'runtime.js')
